// Command kafkagen reads Kafka protocol message definitions from a directory
// of JSON specs and generates Go decoders into a target package directory.
//
// Each request/response/header/data spec produces one file (snake_case of the
// message name) with struct types and a Decode method. A dispatch.go file is
// also emitted with UnmarshalRequest and UnmarshalResponse top-level helpers.
//
//go:generate go run ./... -in ../../message -out ../../
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

func main() {
	var inDir, outDir string
	flag.StringVar(&inDir, "in", "message", "directory of Kafka JSON spec files")
	flag.StringVar(&outDir, "out", "kafkaproto", "directory to write generated Go files into")
	flag.Parse()

	if err := run(inDir, outDir); err != nil {
		log.Fatal(err)
	}
}

func run(inDir, outDir string) error {
	entries, err := os.ReadDir(inDir)
	if err != nil {
		return fmt.Errorf("read %s: %w", inDir, err)
	}

	// Clean previously generated files (anything tagged with our header).
	if err := cleanGenerated(outDir); err != nil {
		return err
	}

	var specs []*Spec
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".json") {
			continue
		}
		path := filepath.Join(inDir, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return fmt.Errorf("read %s: %w", path, err)
		}
		spec, err := ParseSpec(data)
		if err != nil {
			return fmt.Errorf("parse %s: %w", path, err)
		}
		if spec.Valid.None {
			// "validVersions": "none" — message is deprecated/unsupported.
			continue
		}
		specs = append(specs, spec)
	}

	sort.Slice(specs, func(i, j int) bool { return specs[i].Name < specs[j].Name })

	for _, spec := range specs {
		out, err := EmitMessageFile(spec)
		if err != nil {
			return fmt.Errorf("emit %s: %w", spec.Name, err)
		}
		path := filepath.Join(outDir, snakeCase(spec.Name)+".go")
		if err := os.WriteFile(path, out, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", path, err)
		}
	}

	dispatch, err := EmitDispatch(specs)
	if err != nil {
		return fmt.Errorf("emit dispatch: %w", err)
	}
	path := filepath.Join(outDir, "dispatch.go")
	if err := os.WriteFile(path, dispatch, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", path, err)
	}

	log.Printf("kafkagen: wrote %d message files + dispatch.go", len(specs))
	return nil
}

const generatedHeader = "// Code generated by cmd/kafkagen. DO NOT EDIT."

// cleanGenerated removes every .go file in outDir that begins with our generated
// header. Hand-written files (reader.go, gen.go, ...) are left alone.
func cleanGenerated(outDir string) error {
	entries, err := os.ReadDir(outDir)
	if err != nil {
		return fmt.Errorf("read %s: %w", outDir, err)
	}
	for _, entry := range entries {
		if entry.IsDir() || !strings.HasSuffix(entry.Name(), ".go") {
			continue
		}
		path := filepath.Join(outDir, entry.Name())
		data, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if bytes.HasPrefix(data, []byte(generatedHeader)) {
			if err := os.Remove(path); err != nil {
				return err
			}
		}
	}
	return nil
}

func snakeCase(s string) string {
	var b strings.Builder
	for i, r := range s {
		if i > 0 && r >= 'A' && r <= 'Z' {
			b.WriteByte('_')
		}
		if r >= 'A' && r <= 'Z' {
			b.WriteRune(r + ('a' - 'A'))
		} else {
			b.WriteRune(r)
		}
	}
	return b.String()
}

func gofmt(src []byte) ([]byte, error) {
	out, err := format.Source(src)
	if err != nil {
		// Return the unformatted source alongside the error so the user can see
		// which line tripped gofmt; helps debug generator bugs.
		return src, fmt.Errorf("gofmt: %w\n--- source ---\n%s", err, src)
	}
	return out, nil
}

// EmitDispatch generates the top-level UnmarshalRequest / UnmarshalResponse helpers.
func EmitDispatch(specs []*Spec) ([]byte, error) {
	e := &emitter{}
	e.line(generatedHeader)
	e.line("")
	e.line("package kafkaproto")
	e.line("")
	e.line("import \"fmt\"")
	e.line("")
	e.line("// Message is implemented by every generated request/response struct.")
	e.line("type Message interface {")
	e.line("\tDecode(r *Reader, version int16) error")
	e.line("\tEncode(w *Writer, version int16) error")
	e.line("}")
	e.line("")

	emitDispatchFn(e, "UnmarshalRequest", "request", specs)
	emitDispatchFn(e, "UnmarshalResponse", "response", specs)

	emitErrorResponseFn(e, specs)

	emitRequestHeaderCodec(e, specs)
	emitFlexibleSwitch(e, "responseHeaderFlexible", "response", specs)

	return gofmt(e.buf.Bytes())
}

// emitRequestHeaderCodec writes free-standing ReadRequestHeader and
// WriteRequestHeader helpers. For flexible (apiKey, apiVersion) combinations
// the read path consumes the trailing tagged-fields count and the write path
// emits an empty tagged-fields block. Flexibility is determined per apiKey
// from the request spec's flexibleVersions.
func emitRequestHeaderCodec(e *emitter, specs []*Spec) {
	e.line("// ReadRequestHeader decodes a Kafka request header. For flexible (apiKey,")
	e.line("// apiVersion) combinations it also consumes the trailing tagged-fields count,")
	e.line("// leaving r positioned at the start of the request body.")
	e.line("func (r *Reader) ReadRequestHeader() (apiKey int16, apiVersion int16, corrID int32, clientID *string, err error) {")
	e.line("\tapiKey, err = r.ReadInt16()")
	e.line("\tif err != nil { return }")
	e.line("\tapiVersion, err = r.ReadInt16()")
	e.line("\tif err != nil { return }")
	e.line("\tcorrID, err = r.ReadInt32()")
	e.line("\tif err != nil { return }")
	e.line("\tclientID, err = r.ReadNullableString()")
	e.line("\tif err != nil { return }")
	e.line("\tif requestHeaderFlexible(apiKey, apiVersion) {")
	e.line("\t\tif err = r.ReadTaggedFields(nil); err != nil { return }")
	e.line("\t}")
	e.line("\treturn")
	e.line("}")
	e.line("")
	e.line("// WriteRequestHeader encodes a Kafka request header (apiKey, apiVersion,")
	e.line("// correlation id, client id). For flexible (apiKey, apiVersion) combinations")
	e.line("// it also writes an empty tagged-fields block.")
	e.line("func (w *Writer) WriteRequestHeader(apiKey int16, apiVersion int16, corrID int32, clientID *string) {")
	e.line("\tw.WriteInt16(apiKey)")
	e.line("\tw.WriteInt16(apiVersion)")
	e.line("\tw.WriteInt32(corrID)")
	e.line("\tw.WriteNullableString(clientID)")
	e.line("\tif requestHeaderFlexible(apiKey, apiVersion) {")
	e.line("\t\tw.WriteTaggedFields(nil)")
	e.line("\t}")
	e.line("}")
	e.line("")
	emitFlexibleSwitch(e, "requestHeaderFlexible", "request", specs)
}

func emitFlexibleSwitch(e *emitter, fnName, kind string, specs []*Spec) {
	byKey := map[int]*Spec{}
	for _, s := range specs {
		if s.Type != kind || !s.HasAPIKey {
			continue
		}
		byKey[s.APIKey] = s
	}
	keys := make([]int, 0, len(byKey))
	for k := range byKey {
		keys = append(keys, k)
	}
	sort.Ints(keys)

	e.line("func %s(apiKey, apiVersion int16) bool {", fnName)
	e.line("\t_ = apiVersion")
	e.line("\tswitch apiKey {")
	for _, k := range keys {
		s := byKey[k]
		// KIP-511: the ApiVersions response header is pinned to v0 so an old
		// client can still parse ErrorCode when the broker speaks a newer
		// protocol than it understands. The request side is unaffected.
		if kind == "response" && k == 18 {
			e.line("\tcase %d: // %s — KIP-511: response header pinned to v0", k, s.Name)
			e.line("\t\treturn false")
			continue
		}
		cond := s.Flexible.Condition("apiVersion")
		e.line("\tcase %d: // %s", k, s.Name)
		e.line("\t\treturn %s", cond)
	}
	e.line("\t}")
	e.line("\treturn false")
	e.line("}")
	e.line("")
}

// topLevelField returns the top-level field of s with the given name, or nil.
func topLevelField(s *Spec, name string) *Field {
	for _, f := range s.Fields {
		if f.Name == name {
			return f
		}
	}
	return nil
}

// elementField returns the named field on a struct-typed array element, or nil.
func elementField(s *Spec, arr *Field, name string) *Field {
	if arr.Kind != KindArray || arr.Elem == nil || arr.Elem.Kind != KindStruct {
		return nil
	}
	st := s.Structs[arr.Elem.StructName]
	if st == nil {
		return nil
	}
	for _, f := range st.Fields {
		if f.Name == name {
			return f
		}
	}
	return nil
}

// arrayAction describes the population of one top-level response array from
// one top-level request array. The two arrays may have different names when
// the action comes from the single-array fallback (see buildEntry). Items are
// always appended to the response array, so multiple actions can coexist —
// for instance AlterUserScramCredentials feeds both Deletions and Upsertions
// into the same Results array.
type arrayAction struct {
	respArrayName string // field name on the response struct
	reqArrayName  string // field name on the request struct (often equal)
	respElemType  string
	condition     string
	msgCondition  string
	// reqElemIsStruct is false when the request array is a scalar slice (e.g.
	// []string). copies then reference the loop value directly via source="".
	reqElemIsStruct bool
	copies          []copyOp
}

// copyOp describes one scalar assignment from a request loop binding into a
// response element field.
type copyOp struct {
	// respField is the name of the field on the response element to assign.
	respField string
	// source is the name of the field on the request element (when iterating
	// a struct array), or "" to mean the loop value itself (when iterating a
	// scalar slice).
	source string
	// takeAddress emits a leading `&` — used when the request supplies a
	// string and the response stores a *string.
	takeAddress bool
}

// responseEntry collects everything we need to emit one case clause of
// ErrorResponse: the request type to type-switch on, the response struct to
// construct, and the actions (top-level + per-array) that populate it.
type responseEntry struct {
	req, resp *Spec
	// outerCondition gates the entire case body. It is the disjunction of
	// every action's condition (so at least one action fires whenever it
	// evaluates true). "true" means unconditional.
	outerCondition string
	// topCondition is non-empty iff the response has a top-level ErrorCode
	// field; it gates `m.ErrorCode = errorCode`.
	topCondition string
	// topMsgCondition is non-empty iff the response has a top-level
	// ErrorMessage field; it gates `m.ErrorMessage = errorMessage`.
	topMsgCondition string
	arrays          []arrayAction
}

// isCopyableScalar reports whether fields of this Kind can be assigned
// directly from a request struct to a response struct (no allocation or
// conversion needed).
func isCopyableScalar(k FieldKind) bool {
	switch k {
	case KindBool, KindInt8, KindInt16, KindUint16, KindInt32, KindUint32,
		KindInt64, KindFloat64, KindString, KindUUID:
		return true
	}
	return false
}

// buildEntry computes the responseEntry for an (apiKey) request/response pair,
// or returns false if no error information can be conveyed.
//
// Matching has two modes:
//
//  1. Name-matched: for every top-level response array with an ErrorCode in
//     its element struct, look for a top-level request array with the same
//     name. Used for any response whose error info isn't carried only by a
//     single per-item array (i.e. when there's a top-level ErrorCode and/or
//     multiple top-level arrays in the response).
//
//  2. Single-array fallback: when the response has no top-level ErrorCode and
//     exactly one top-level array (with an ErrorCode-bearing element), any
//     top-level request array may feed into it regardless of name. Scalar
//     []string request arrays are paired to a response element field via
//     entityType. This covers DeleteTopics (Topics + TopicNames → Responses),
//     DescribeGroups family (GroupIds → Groups), CreateAcls (Creations →
//     Results), and similar shapes.
func buildEntry(req, resp *Spec) (responseEntry, bool) {
	ent := responseEntry{req: req, resp: resp}
	var conds []string

	// Top-level ErrorCode.
	hasTopErrorCode := false
	if ec := topLevelField(resp, "ErrorCode"); ec != nil && ec.Kind == KindInt16 {
		if rng := resp.Valid.Intersect(ec.Versions); !rng.None {
			ent.topCondition = rng.Condition("apiVersion")
			conds = append(conds, ent.topCondition)
			hasTopErrorCode = true
			// Top-level ErrorMessage is only meaningful together with
			// top-level ErrorCode.
			if em := topLevelField(resp, "ErrorMessage"); em != nil && em.Kind == KindString && !em.Nullable.None {
				if mrng := rng.Intersect(em.Versions); !mrng.None {
					ent.topMsgCondition = mrng.Condition("apiVersion")
				}
			}
		}
	}

	// Collect top-level response arrays whose element struct carries an
	// int16 ErrorCode. Anything else can't convey a per-item error.
	var respArrays []*Field
	for _, rf := range resp.Fields {
		if rf.Kind != KindArray || rf.Elem == nil || rf.Elem.Kind != KindStruct {
			continue
		}
		if ec := elementField(resp, rf, "ErrorCode"); ec == nil || ec.Kind != KindInt16 {
			continue
		}
		respArrays = append(respArrays, rf)
	}

	switch {
	case !hasTopErrorCode && len(respArrays) == 1:
		// Single-array fallback: feed every top-level request array into the
		// one response array, regardless of name.
		respArr := respArrays[0]
		for _, qf := range req.Fields {
			if qf.Kind != KindArray {
				continue
			}
			act := buildArrayAction(resp, respArr, req, qf, true)
			if act == nil {
				continue
			}
			ent.arrays = append(ent.arrays, *act)
			conds = append(conds, act.condition)
		}
	default:
		// Name-matched: pair each response array with a same-named request array.
		for _, rf := range respArrays {
			qf := topLevelField(req, rf.Name)
			if qf == nil || qf.Kind != KindArray {
				continue
			}
			act := buildArrayAction(resp, rf, req, qf, false)
			if act == nil {
				continue
			}
			ent.arrays = append(ent.arrays, *act)
			conds = append(conds, act.condition)
		}
	}

	if ent.topCondition == "" && len(ent.arrays) == 0 {
		return responseEntry{}, false
	}

	// Build the outer condition as the OR of every action's condition.
	// Collapse to "true" when any action fires unconditionally.
	outer := strings.Join(uniqueNonEmpty(conds), " || ")
	for _, c := range conds {
		if c == "true" {
			outer = "true"
			break
		}
	}
	ent.outerCondition = outer
	return ent, true
}

// buildArrayAction constructs an arrayAction for one (request array, response
// array) pair. fallback=true relaxes element-kind requirements so we can
// handle []string request arrays in the single-array fallback mode. Returns
// nil when the pair can't be wired up at any version.
func buildArrayAction(resp *Spec, respArr *Field, req *Spec, reqArr *Field, fallback bool) *arrayAction {
	if reqArr.Elem == nil {
		return nil
	}
	respEC := elementField(resp, respArr, "ErrorCode")
	if respEC == nil {
		return nil
	}

	// In name-matched mode both sides must be struct arrays so we can pair
	// fields by name. In the single-array fallback we also accept scalar
	// request slices (typically []string with an entityType).
	reqElemIsStruct := reqArr.Elem.Kind == KindStruct
	if !reqElemIsStruct && !fallback {
		return nil
	}
	if !reqElemIsStruct && !isCopyableScalar(reqArr.Elem.Kind) {
		return nil
	}

	rng := resp.Valid.Intersect(respArr.Versions).Intersect(reqArr.Versions).Intersect(respEC.Versions)
	if rng.None {
		return nil
	}

	act := &arrayAction{
		respArrayName:   respArr.Name,
		reqArrayName:    reqArr.Name,
		respElemType:    goTypeName(resp.Name, respArr.Elem.StructName),
		condition:       rng.Condition("apiVersion"),
		reqElemIsStruct: reqElemIsStruct,
	}
	if em := elementField(resp, respArr, "ErrorMessage"); em != nil && em.Kind == KindString && !em.Nullable.None {
		if mrng := rng.Intersect(em.Versions); !mrng.None {
			act.msgCondition = mrng.Condition("apiVersion")
		}
	}

	respElemS := resp.Structs[respArr.Elem.StructName]
	if respElemS == nil {
		return act
	}
	if reqElemIsStruct {
		reqElemS := req.Structs[reqArr.Elem.StructName]
		if reqElemS != nil {
			act.copies = structCopies(resp, respElemS, req, reqElemS)
		}
	} else if op := scalarCopy(resp, respElemS, reqArr.Elem); op != nil {
		act.copies = []copyOp{*op}
	}
	return act
}

// structCopies derives the per-field assignments to make when the request
// element is also a struct. Fields are matched by name first; failing that,
// by entityType so the spec's semantic links (topicName, groupId, …) carry
// across renames like Deletions.Name ↦ Results.User.
func structCopies(resp *Spec, respElemS *Struct, req *Spec, reqElemS *Struct) []copyOp {
	reqByName := map[string]*Field{}
	reqByEntity := map[string]*Field{}
	for _, x := range reqElemS.Fields {
		reqByName[x.Name] = x
		if x.EntityType != "" {
			reqByEntity[x.EntityType] = x
		}
	}
	used := map[string]bool{} // request field names already claimed
	var out []copyOp
	for _, ef := range respElemS.Fields {
		if ef.Name == "ErrorCode" || ef.Name == "ErrorMessage" {
			continue
		}
		if !isCopyableScalar(ef.Kind) {
			continue
		}
		if qef, ok := reqByName[ef.Name]; ok && !used[qef.Name] {
			if op := buildScalarOp(resp, ef, req, qef, ef.Name); op != nil {
				out = append(out, *op)
				used[qef.Name] = true
				continue
			}
		}
		if ef.EntityType != "" {
			if qef, ok := reqByEntity[ef.EntityType]; ok && !used[qef.Name] {
				if op := buildScalarOp(resp, ef, req, qef, qef.Name); op != nil {
					out = append(out, *op)
					used[qef.Name] = true
				}
			}
		}
	}
	return out
}

// scalarCopy builds the single assignment for a scalar request slice (e.g.
// []string) by finding a response element field whose entityType matches
// the slice's entityType.
func scalarCopy(resp *Spec, respElemS *Struct, reqElem *Field) *copyOp {
	if reqElem.EntityType == "" {
		return nil
	}
	for _, ef := range respElemS.Fields {
		if ef.EntityType != reqElem.EntityType {
			continue
		}
		if !isCopyableScalar(ef.Kind) || ef.Kind != reqElem.Kind {
			continue
		}
		op := &copyOp{respField: ef.Name, source: ""}
		// String scalars in the request are always plain `string`; the
		// response field may be *string when nullable.
		if ef.Kind == KindString && goFieldType(resp, ef) == "*string" {
			op.takeAddress = true
		}
		return op
	}
	return nil
}

// buildScalarOp constructs a copyOp for matching scalar fields, handling the
// common *string vs string mismatch by taking the address of the request
// value. source is the field name on the request element to read from.
func buildScalarOp(resp *Spec, ef *Field, req *Spec, qef *Field, source string) *copyOp {
	if ef.Kind != qef.Kind {
		return nil
	}
	respGo := goFieldType(resp, ef)
	reqGo := goFieldType(req, qef)
	if respGo == reqGo {
		return &copyOp{respField: ef.Name, source: source}
	}
	// *string ← string: take the address of the request field.
	if ef.Kind == KindString && respGo == "*string" && reqGo == "string" {
		return &copyOp{respField: ef.Name, source: source, takeAddress: true}
	}
	// Other type mismatches (e.g. string ← *string requires nil checks) are
	// skipped to keep the generator honest about what it can synthesise.
	return nil
}

func uniqueNonEmpty(in []string) []string {
	seen := map[string]bool{}
	out := in[:0]
	for _, s := range in {
		if s == "" || seen[s] {
			continue
		}
		seen[s] = true
		out = append(out, s)
	}
	return out
}

// emitErrorResponseFn writes the ErrorResponse helper: dispatch on the
// request type and build a response populated with errorCode (and
// errorMessage when applicable) — at the top level when the response carries
// ErrorCode/ErrorMessage directly, and per-item for each top-level request
// array that maps into a top-level response array. See buildEntry for the
// matching rules.
func emitErrorResponseFn(e *emitter, specs []*Spec) {
	// Pair up request and response by apiKey.
	type pair struct{ req, resp *Spec }
	pairs := map[int]pair{}
	for _, s := range specs {
		if !s.HasAPIKey {
			continue
		}
		p := pairs[s.APIKey]
		switch s.Type {
		case "request":
			p.req = s
		case "response":
			p.resp = s
		}
		pairs[s.APIKey] = p
	}

	entries := map[int]responseEntry{}
	for k, p := range pairs {
		if p.req == nil || p.resp == nil {
			continue
		}
		ent, ok := buildEntry(p.req, p.resp)
		if !ok {
			continue
		}
		entries[k] = ent
	}
	keys := make([]int, 0, len(entries))
	for k := range entries {
		keys = append(keys, k)
	}
	sort.Ints(keys)

	e.line("// ErrorResponse synthesises an error response for req at apiVersion, with")
	e.line("// errorCode applied to every top-level error field the response exposes:")
	e.line("// the response's top-level ErrorCode (and ErrorMessage) when present, and")
	e.line("// one entry per request item for each top-level request array that maps")
	e.line("// into a top-level response array. Same-named arrays pair up directly; if")
	e.line("// the response has just a single top-level array and no top-level")
	e.line("// ErrorCode, any top-level request array (struct or scalar slice) is fed")
	e.line("// into it, with scalar copies propagated by matching field name or by the")
	e.line("// spec's entityType annotation. Returns an error when no response is")
	e.line("// paired with req's type, or when apiVersion is outside the range in which")
	e.line("// the response can carry the error on the wire.")
	e.line("func ErrorResponse(req Message, apiVersion int16, errorCode int16, errorMessage *string) (Message, error) {")
	e.line("\tswitch r := req.(type) {")
	for _, k := range keys {
		ent := entries[k]
		e.line("\tcase *%s:", ent.req.Name)
		// If we'll never reference r in this case body (no array actions), the
		// type switch still allows the unused binding — Go does not flag case
		// variables. But emitting a discard keeps the generated code obvious.
		if len(ent.arrays) == 0 {
			e.line("\t\t_ = r")
		}
		indent := "\t\t"
		if ent.outerCondition != "true" {
			e.line("\t\tif %s {", ent.outerCondition)
			indent = "\t\t\t"
		}
		e.line("%sm := &%s{}", indent, ent.resp.Name)
		emitEntryBody(e, ent, indent)
		e.line("%sreturn m, nil", indent)
		if ent.outerCondition != "true" {
			e.line("\t\t}")
		}
	}
	e.line("\t}")
	e.line("\treturn nil, fmt.Errorf(\"kafkaproto: no error response available for %%T at apiVersion %%d\", req, apiVersion)")
	e.line("}")
	e.line("")
}

// emitEntryBody writes the populate statements inside a case, gating each
// action with its own condition when it's narrower than the outer condition.
func emitEntryBody(e *emitter, ent responseEntry, indent string) {
	// Top-level ErrorCode.
	if ent.topCondition != "" {
		emitGated(e, indent, ent.topCondition, ent.outerCondition, func(inner string) {
			e.line("%sm.ErrorCode = errorCode", inner)
			if ent.topMsgCondition != "" && ent.topMsgCondition == ent.topCondition {
				e.line("%sm.ErrorMessage = errorMessage", inner)
			}
		})
		// ErrorMessage with a strictly narrower range needs its own gate.
		if ent.topMsgCondition != "" && ent.topMsgCondition != ent.topCondition {
			emitGated(e, indent, ent.topMsgCondition, ent.outerCondition, func(inner string) {
				e.line("%sm.ErrorMessage = errorMessage", inner)
			})
		}
	}

	// Per-array iterations. Items are appended so multiple actions writing
	// into the same response array (e.g. Deletions + Upsertions → Results)
	// concatenate naturally.
	for _, act := range ent.arrays {
		emitArrayAction(e, ent, act, indent)
	}
}

// emitArrayAction writes the loop that feeds one request array into the
// response array, gating the loop on the action's version range and the
// per-element ErrorMessage on its own (potentially narrower) range.
func emitArrayAction(e *emitter, ent responseEntry, act arrayAction, indent string) {
	emitGated(e, indent, act.condition, ent.outerCondition, func(inner string) {
		loopVar := "it"
		if !act.reqElemIsStruct {
			loopVar = "v"
		}
		needLoopVar := len(act.copies) > 0
		if needLoopVar {
			e.line("%sfor _, %s := range r.%s {", inner, loopVar, act.reqArrayName)
		} else {
			e.line("%sfor range r.%s {", inner, act.reqArrayName)
		}
		body := inner + "\t"
		e.line("%sitem := %s{}", body, act.respElemType)
		for _, c := range act.copies {
			expr := loopVar
			if c.source != "" {
				expr = loopVar + "." + c.source
			}
			if c.takeAddress {
				expr = "&" + expr
			}
			e.line("%sitem.%s = %s", body, c.respField, expr)
		}
		e.line("%sitem.ErrorCode = errorCode", body)
		if act.msgCondition != "" {
			if act.msgCondition == "true" || act.msgCondition == act.condition {
				e.line("%sitem.ErrorMessage = errorMessage", body)
			} else {
				e.line("%sif %s {", body, act.msgCondition)
				e.line("%s\titem.ErrorMessage = errorMessage", body)
				e.line("%s}", body)
			}
		}
		e.line("%sm.%s = append(m.%s, item)", body, act.respArrayName, act.respArrayName)
		e.line("%s}", inner)
	})
}

// emitGated emits body inside an `if cond { ... }` block, unless cond is
// already implied by outer (or is trivially "true"), in which case body is
// emitted directly at indent.
func emitGated(e *emitter, indent, cond, outer string, body func(inner string)) {
	if cond == "true" || cond == outer {
		body(indent)
		return
	}
	e.line("%sif %s {", indent, cond)
	body(indent + "\t")
	e.line("%s}", indent)
}

func emitDispatchFn(e *emitter, fnName, kind string, specs []*Spec) {
	// Group by apiKey, picking the matching kind.
	byKey := map[int]*Spec{}
	for _, s := range specs {
		if s.Type != kind || !s.HasAPIKey {
			continue
		}
		byKey[s.APIKey] = s
	}
	keys := make([]int, 0, len(byKey))
	for k := range byKey {
		keys = append(keys, k)
	}
	sort.Ints(keys)

	e.line("// %s decodes a Kafka %s body from r (positioned after the request/response", fnName, kind)
	e.line("// header) into the appropriate generated struct, dispatched on apiKey.")
	e.line("func %s(r *Reader, apiKey, apiVersion int16) (m Message, err error) {", fnName)
	e.line("\tswitch apiKey {")
	for _, k := range keys {
		s := byKey[k]
		e.line("\tcase %d:", k)
		e.line("\t\tm = &%s{}", s.Name)
	}
	e.line("\tdefault:")
	e.line("\t\treturn m, fmt.Errorf(\"kafkaproto: unsupported %s apiKey %%d\", apiKey)", kind)
	e.line("\t}")
	e.line("\tif err = m.Decode(r, apiVersion); err != nil {")
	e.line("\t\treturn")
	e.line("\t}")
	e.line("\treturn")
	e.line("}")
	e.line("")
}
